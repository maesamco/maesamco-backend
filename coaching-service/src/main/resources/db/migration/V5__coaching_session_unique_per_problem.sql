-- 코칭 세션을 "문제당 평생 최대 1개"로 되돌린다(2026-09-03 재검토, 이슈 #84).
--
-- 배경: V4는 "진행 중(IN_PROGRESS)인 세션은 문제당 최대 1개"만 부분 UNIQUE 인덱스로
-- 강제해서, 세션이 COMPLETED되면 그 문제를 다시 도전할 때 새 세션이 열릴 수 있었다
-- (이미 정답을 맞춘 문제를 나중에 다시 풀어보는 시나리오를 막지 않으려는 의도).
--
-- 그런데 #50(60초 설명 등록/조회 API) 설계 중, 이 구조가 실제로 문제를 낳는 걸
-- 발견했다 — 설명(p_explanations)은 코칭 세션 단위로 저장되는데, 완료된 세션 뒤에
-- 같은 문제를 다시 풀면 같은 (user_id, problem_id)에 세션이 여러 개 존재하게 되고,
-- 조회 API가 어느 세션의 설명을 반환해야 하는지 정의할 수 없었다.
--
-- 재검토 결과: 이미 코칭이 완료된 문제를 연습 목적으로 재제출해도 60초 설명·역질문
-- 코칭 의식을 다시 시킬 필요는 없다고 판단, "문제당 세션은 평생 최대 1개"로
-- 되돌린다. 완료된 문제를 다시 정답 제출하면 기존(완료된) 세션을 그대로 재사용한다.
--
-- ⚠️ 2026-09-03 PR #88 리뷰(용현님 P3) 정정: 위 문단이 작성된 시점엔 설명(p_explanations)의
-- 유일성 기준이 coaching_session_id였어서 "재도전으로 재등록을 시도하면
-- EXPLANATION_ALREADY_EXISTS(409)로 막힌다"고 서술했으나, 같은 PR의 V6(이슈 #84 결정 2)에서
-- 그 기준이 submission_id로 바뀌었다 — 세션은 하나로 유지되지만, 재도전으로 새로 정답
-- 제출할 때마다 그 submission_id 기준으로 별도 설명을 등록할 수 있다(더 이상 막히지 않음).
-- 자세한 배경은 V6 마이그레이션 파일 참고.
--
-- 부수 효과: 이슈 #73(세션 COMPLETED 후 재도전 시 힌트 예산이 매번 리셋되는 문제)도
-- 이 변경으로 근본적으로 해소된다 — 완료 후엔 새 세션이 아예 안 생기므로 힌트 예산도
-- 리셋될 여지가 없다.
--
-- V4와 동일하게, 이 프로젝트는 아직 실사용자 데이터가 없는 개발 단계라(seed 데이터
-- 없음) 기존 데이터 정리 없이 인덱스만 교체한다. 나중에 실제 데이터가 쌓인 뒤 이
-- 마이그레이션을 다시 적용해야 하는 상황이 오면, 먼저 동일 (user_id, problem_id)
-- 중복 행 정리 절차를 마이그레이션에 포함시킬 것.

DROP INDEX coaching_schema.uk_coaching_sessions_user_problem_in_progress;

CREATE UNIQUE INDEX uk_coaching_sessions_user_problem
    ON coaching_schema.p_coaching_sessions (user_id, problem_id);
